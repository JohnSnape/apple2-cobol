* RPTEXP.S  REPORT: generate the COBOL
* PUT from REPORT.S - no ORG, not assembled alone.
* One symbol table spans every PUT: this file and
* REPORT resolve against each other in pass two.
*
* Slices 6 and 7 (REPORT.md section 9), written
* 2026-11-08.  OA-E exports, SA-C shows the same
* code on the screen.  ONE WALK, TWO SINKS: the
* lines are built one at a time in RXLN and handed
* to RXOUT, which writes them to the .SNP or draws
* them, so what is shown is what is written.
*
* WHAT COMES OUT - every statement in it is one the
* compiler takes today (KEYWORDS.md, FIXLIST.md):
*   * NAME  generated by REPORT
*   01 RPT-PAGE, RPT-LINES          the counters
*   01 RPT-DATE, RPT-DATEP          if there is a date
*   01 RT-nn  S9(..)V..             one per TOTAL
*   01 RPT-Lnn, one per page line that has entries:
*      FILLER gaps, FILLER literals and rules, and a
*      named R<line>-<col> item for every field,
*      total, page number and date
*   *                               (a lone star)
*   RPT-BEGIN   zero, date, first heading
*   RPT-HEAD    the lines above the detail band
*   RPT-DETAIL  break the page if the band will not
*               fit, add the totals, print the band
*   RPT-FOOT    fill to the footing, print it, fill
*               to the end of the page
*   RPT-SKIP    one blank line
*   RPT-END     the last footing
* The lone star splits data from paragraphs, so the
* editor's PLACE (SA-P, R) puts each where it goes.
* Lines and columns in the names are 1-based, as the
* prompts are: R05-12 is page line 5, column 12.

* table lengths, here and not by the tables: an EQU
* must come before its first use in Merlin 8
RXDTN EQU 20
RXBTN EQU 8

