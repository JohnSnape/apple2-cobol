* DISKIO.S  save/load a form as a .DCT file
* Needs PRODOS.S (WRDCT, DICTLOAD, GET_PREFIX,
* ON_LINE) and the form model arrays (FCOUNT,
* RECTOT, EROWS, ELCOLS, EFCOLS, ETYPES, EWIDS,
* EFLGS, ESTORS, ERECL, ERECH, ELTEXT) defined by
* the caller (FORMAT or a test).
* MKPATH: NAMEBUF -> FULLPATH + PATHAD.
* SAVEDCT: build .DCT from arrays, write it.

